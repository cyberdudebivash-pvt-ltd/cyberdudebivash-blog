function isKnownPlatform(platformId) {
  return Object.prototype.hasOwnProperty.call(KNOWN_PLATFORMS, platformId);
}

function capabilitiesFor(platformId) {
  return (KNOWN_PLATFORMS[platformId] && KNOWN_PLATFORMS[platformId].capabilities) || null;
}

